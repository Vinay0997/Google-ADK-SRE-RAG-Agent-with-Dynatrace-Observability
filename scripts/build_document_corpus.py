def slugify(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def sql_string(value: str) -> str:
    """Escape a Python string as a double-quoted BigQuery string literal.

    Newlines are embedded literally; BigQuery string literals may span lines.
    """
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build_seed_sql(docs: list[dict]) -> str:
    lines = [
        "-- Seed the Aurelius Health Systems policy document corpus into the",
        "-- BigQuery vector index. Source of truth: knowledge/documents.json",
        "-- (generated by scripts/build_document_corpus.py from documents/Markdown/).",
        "-- Replace semantics: deletes documents no longer in the corpus, then",
        "-- upserts all current documents. Idempotent. The table name",
        "-- runbook_chunks is retained for deploy compatibility.",
        "",
        "DELETE FROM `adk-dynatrace-observability.agent_observability.runbook_chunks`",
        "WHERE doc_id NOT IN (",
    ]
    ids = [f"  {sql_string(d['id'])}" for d in docs]
    lines.append(",\n".join(ids))
    lines.append(");")
    lines.append("")
    lines.append("CREATE TEMP TABLE generated_documents AS")
    lines.append("SELECT *")
    lines.append("FROM AI.GENERATE_EMBEDDING(")
    lines.append("  MODEL `adk-dynatrace-observability.agent_observability.embedding_model`,")
    lines.append("  (")
    selects = []
    for d in docs:
        selects.append(
            "    SELECT\n"
            f"      {sql_string(d['id'])} AS doc_id,\n"
            f"      {sql_string(d['title'])} AS title,\n"
            f"      {sql_string(d['content'])} AS content,\n"
            f"      {sql_string(d['category'])} AS category,\n"
            f"      {sql_string(d['source'])} AS source,\n"
            f"      [{', '.join(sql_string(r) for r in d['allowed_roles'])}] AS allowed_roles"
        )
    lines.append("\n    UNION ALL\n".join(selects))
    lines.append("  ),")
    lines.append("  STRUCT(")
    lines.append("    'RETRIEVAL_DOCUMENT' AS task_type,")
    lines.append("    768 AS output_dimensionality")
    lines.append("  )")
    lines.append(");")
    lines.append("")
    lines.append("ASSERT (")
    lines.append(f"  SELECT COUNT(*) = {len(docs)}")
    lines.append("  FROM generated_documents")
    lines.append("  WHERE status = ''")
    lines.append("    AND ARRAY_LENGTH(embedding) = 768")
    lines.append(") AS 'Embedding generation failed or returned unexpected dimensions';")
    lines.append("")
    lines.append("MERGE `adk-dynatrace-observability.agent_observability.runbook_chunks` AS target")
    lines.append("USING generated_documents AS incoming")
    lines.append("ON target.doc_id = incoming.doc_id")
    lines.append("WHEN MATCHED THEN")
    lines.append("  UPDATE SET")
    lines.append("    embedding = incoming.embedding,")
    lines.append("    statistics = incoming.statistics,")
    lines.append("    status = incoming.status,")
    lines.append("    title = incoming.title,")
    lines.append("    content = incoming.content,")
    lines.append("    category = incoming.category,")
    lines.append("    source = incoming.source,")
    lines.append("    allowed_roles = incoming.allowed_roles")
    lines.append("WHEN NOT MATCHED THEN")
    lines.append("  INSERT (")
    lines.append("    embedding, statistics, status, doc_id, title,")
    lines.append("    content, category, source, allowed_roles")
    lines.append("  )")
    lines.append("  VALUES (")
    lines.append("    incoming.embedding, incoming.statistics, incoming.status,")
    lines.append("    incoming.doc_id, incoming.title, incoming.content,")
    lines.append("    incoming.category, incoming.source, incoming.allowed_roles")
    lines.append("  );")
    lines.append("")
    lines.append("SELECT")
    lines.append("  doc_id,")
    lines.append("  title,")
    lines.append("  allowed_roles,")
    lines.append("  ARRAY_LENGTH(embedding) AS embedding_dimensions,")
    lines.append("  status")
    lines.append("FROM `adk-dynatrace-observability.agent_observability.runbook_chunks`")
    lines.append("ORDER BY doc_id;")
    return "\n".join(lines) + "\n"


def build() -> None:
    docs = []
    for path in sorted(SOURCE_DIR.glob("*.md")):
        text = path.read_text(encoding="utf-8").strip()
        title_match = re.match(r"#\s+(.+)", text)
        title = title_match.group(1).strip() if title_match else path.stem
        doc_type = (re.search(r"\*\*Document Type:\*\*\s*(.+)", text) or [None, ""])[1].strip()
        department = (re.search(r"\*\*Department:\*\*\s*(.+)", text) or [None, ""])[1].strip()

        doc_id = slugify(path.stem)
        tags = sorted(
            {
                token
                for token in re.findall(r"[a-z0-9]+", title.lower())
                if len(token) > 2 and token not in STOPWORDS
            }
            | {
                token
                for token in re.findall(r"[a-z0-9]+", doc_type.lower())
                if len(token) > 2
            }
            | {
                token
                for token in re.findall(r"[a-z0-9]+", department.lower())
                if len(token) > 2
            }
        )

        docs.append(
            {
                "id": doc_id,
                "title": title,
                "tags": tags,
                "content": text,
                "category": doc_type.lower() or "policy",
                "source": f"documents/Markdown/{path.name}",
                "allowed_roles": ROLE_MAP.get(doc_id, ["viewer", "security_privacy"]),
            }
        )

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(docs, indent=2) + "\n", encoding="utf-8")

    seed_path = REPO / "bigquery" / "seed_documents.sql"
    seed_path.parent.mkdir(parents=True, exist_ok=True)
    seed_path.write_text(build_seed_sql(docs), encoding="utf-8")

    print(f"Wrote {len(docs)} documents to {OUTPUT}")
    print(f"Wrote seed SQL to {seed_path}")


if __name__ == "__main__":
    build()
